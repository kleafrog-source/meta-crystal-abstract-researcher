    def generate_and_save_batch(self, count: int = 1000, save_top: int = 3) -> List[Dict]:
        batch = self.generator.generate_batch(count)
        filtered = self.filter.filter_to_emeralds(batch, save_top * 3)

        if filtered and "quality_score" in filtered[0]:
            filtered.sort(key=lambda x: x.get("quality_score", 0), reverse=True)
        else:
            filtered.sort(key=lambda x: x["complexity"], reverse=True)

        top_results = filtered[:save_top]
        saved = []
        for crystal in top_results:
            if self.storage:
                crystal_type = CrystalCatalog.classify(crystal)
                filepath = self.storage.save_crystal(crystal, crystal_type)
                saved.append({"crystal": crystal, "type": crystal_type, "filepath": filepath})
                self.saved_count += 1
        return saved

    def evolve_with_saving(self, generations: int = 3, batch_size: int = 200, save_top: int = 3) -> Dict:
        all_combinations = []

        # v7.1: инициализируем временную сессию генерации
