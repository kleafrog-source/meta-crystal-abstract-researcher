class CrystalStorage:
    """Система хранения и загрузки кристаллов (v7.1: counter/step + temp-index)"""

    def __init__(self, config: EngineConfig):
        self.config = config
        self.output_dir = Path(config.save_config["output_dir"])
        self.catalog_structure = config.save_config["catalog_structure"]
        self.history = []
        self.history_by_type = defaultdict(list)
        # v7.1: счётчик и временный индекс
        self.counter_path = self.output_dir / "meta" / "counter.json"
        self.main_index_path = self.output_dir / "meta" / "index.json"
        self.temp_index_path: Optional[Path] = None  # создаётся в begin_generation()
        self._counter_value: int = 0
        self._ensure_directories()
        self._load_counter()

    def _ensure_directories(self):
        if not self.config.flags["enable_saving"]:
            return
        self.output_dir.mkdir(parents=True, exist_ok=True)
        for catalog in self.catalog_structure.values():
            (self.output_dir / catalog).mkdir(exist_ok=True)
        (self.output_dir / "meta").mkdir(exist_ok=True)

    # ----- v7.1: счётчик -----
    def _load_counter(self):
        """Загружает глобальный счётчик из counter.json. Если файла нет — начинает с 0."""
        if not self.config.flags["enable_saving"]:
            return
        try:
            if self.counter_path.exists():
                data = json.loads(self.counter_path.read_text(encoding="utf-8"))
                self._counter_value = int(data.get("counter", 0))
            else:
                self._counter_value = 0
                self._save_counter()
        except Exception as e:
            print(f"⚠️ Ошибка загрузки counter.json: {e}")
            self._counter_value = 0

    def _save_counter(self):
        """Сохраняет текущее значение счётчика в counter.json."""
        if not self.config.flags["enable_saving"]:
            return
        try:
            self.counter_path.write_text(
                json.dumps({"counter": self._counter_value}, ensure_ascii=False, indent=2),
                encoding="utf-8"
            )
        except Exception as e:
            print(f"⚠️ Ошибка сохранения counter.json: {e}")

    def get_next_counter(self) -> int:
        """Возвращает следующий номер счётчика и инкрементирует его."""
        self._counter_value += 1
        self._save_counter()
        return self._counter_value

    # ----- v7.1: временный индекс -----
    def begin_generation(self, session_id: str = None) -> Path:
        """Начинает новую сессию генерации. Создаёт временный индекс-файл.

        Все save_crystal() в течение сессии пишут только во временный индекс.
        По завершении вызывается merge_index() для слияния с основным index.json.
        """
        if not self.config.flags["enable_saving"]:
            return self.main_index_path
        if session_id is None:
            session_id = datetime.now().strftime("%Y%m%d_%H%M%S") + "_" + hashlib.md5(
                str(datetime.now().timestamp()).encode()).hexdigest()[:6]
        self.temp_index_path = self.output_dir / "meta" / f"index_temp_{session_id}.json"
        # Инициализируем пустой временный индекс
        if not self.temp_index_path.exists():
            initial = {
                "stats": {"total": 0, "by_type": {}, "by_category": {},
                          "last_update": datetime.now().isoformat()},
                "records": []
            }
            self.temp_index_path.write_text(
                json.dumps(initial, ensure_ascii=False, indent=2),
                encoding="utf-8"
            )
        return self.temp_index_path

    def merge_index(self) -> Dict:
        """Сливает временный индекс с основным index.json и удаляет временный файл.

        Возвращает статистику слияния: {"added": N, "total": M}
        """
        if not self.temp_index_path or not self.temp_index_path.exists():
            return {"added": 0, "total": 0, "error": "temp index not found"}

        try:
            temp = json.loads(self.temp_index_path.read_text(encoding="utf-8"))
        except Exception as e:
            return {"added": 0, "total": 0, "error": f"read temp: {e}"}

        # Читаем основной индекс (или создаём пустой)
        if self.main_index_path.exists():
            try:
                main = json.loads(self.main_index_path.read_text(encoding="utf-8"))
            except Exception:
                main = {"stats": {"total": 0, "by_type": {}, "by_category": {}}, "records": []}
        else:
            main = {"stats": {"total": 0, "by_type": {}, "by_category": {}}, "records": []}

        # Сливаем записи
        added = 0
        existing_keys = {(r.get("counter"), r.get("code")) for r in main.get("records", [])}
        for rec in temp.get("records", []):
            key = (rec.get("counter"), rec.get("code"))
            if key not in existing_keys:
                main.setdefault("records", []).append(rec)
                existing_keys.add(key)
                added += 1

        # Пересчитываем статистику полностью
        stats = main.get("stats", {})
        by_type = {}
        by_category = {}
        for r in main.get("records", []):
            t = r.get("type", "unknown")
            c = r.get("category", "unknown")
            by_type[t] = by_type.get(t, 0) + 1
            by_category[c] = by_category.get(c, 0) + 1
        stats["total"] = len(main.get("records", []))
        stats["by_type"] = by_type
        stats["by_category"] = by_category
        stats["last_update"] = datetime.now().isoformat()
        main["stats"] = stats

        # Записываем основной индекс
        self.main_index_path.write_text(
            json.dumps(main, ensure_ascii=False, indent=2),
            encoding="utf-8"
        )

        # Удаляем временный файл
        try:
            self.temp_index_path.unlink()
        except Exception:
            pass
        self.temp_index_path = None

        return {"added": added, "total": stats["total"]}

    def save_crystal(self, crystal: Dict, crystal_type: CrystalType) -> str:
        if not self.config.flags["enable_saving"]:
            return ""

        category = CrystalCatalog.get_category_path(crystal_type)
        code = crystal.get("code", "unknown")
        # v7.1: новый формат имени {counter:07d}_{step:04d}_{code}.json
        counter = self.get_next_counter()
        step = int(crystal.get("step", 0))
        filename = f"{counter:07d}_{step:04d}_{code}.json"
        filepath = self.output_dir / category / filename

        save_data = {
            "meta": {
                "code": code,
                "type": crystal_type.value,
                "category": category,
                "counter": counter,
                "step": step,
                "datetime": datetime.now().isoformat(),
                "generation": crystal.get("generation", 0)
            },
            "crystal": {
                "focus": crystal.get("focus", {}),
                "pattern": crystal.get("pattern", ""),
                "elements": crystal.get("elements", []),
                "operators": crystal.get("operators", []),
                "combination": crystal.get("combination", ""),
                "complexity": crystal.get("complexity", 0),
                "quality_score": crystal.get("quality_score", 0),
                "metrics": crystal.get("metrics", {})
            },
            "classification": {
                "type": crystal_type.value,
                "reasons": self._get_classification_reasons(crystal, crystal_type)
            }
        }

        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(save_data, f, ensure_ascii=False, indent=2)

        self._add_to_history(crystal, crystal_type, filepath)
        self._update_index(crystal, crystal_type, filepath, counter, step)
        return str(filepath)

    def _add_to_history(self, crystal: Dict, crystal_type: CrystalType, filepath: Path):
        entry = {
            "code": crystal.get("code", ""),
            "type": crystal_type.value,
            "category": CrystalCatalog.get_category_path(crystal_type),
            "filepath": str(filepath),
            "timestamp": datetime.now().isoformat(),
            "combination": crystal.get("combination", ""),
            "complexity": crystal.get("complexity", 0),
            "quality_score": crystal.get("quality_score", 0)
        }
        self.history.append(entry)
        self.history_by_type[crystal_type.value].append(entry)

        max_history = self.config.save_config.get("max_history", 1000)
        if len(self.history) > max_history:
            self.history = self.history[-max_history:]

    def _update_index(self, crystal: Dict, crystal_type: CrystalType,
                      filepath: Path, counter: int = 0, step: int = 0):
        """v7.1: пишет во временный индекс, если он активен.
        Если temp_index_path не задан (генерация без сессии) — пишет в основной index.json.
        Формат записи использует counter/step вместо timestamp."""
        if self.temp_index_path and self.temp_index_path.exists():
            index_path = self.temp_index_path
        else:
            index_path = self.main_index_path

        index = {}
        if index_path.exists():
            try:
                with open(index_path, "r", encoding="utf-8") as f:
                    index = json.load(f)
            except Exception:
                index = {}

        if "stats" not in index:
            index["stats"] = {"total": 0, "by_type": {}, "by_category": {}, "last_update": ""}
        if "records" not in index:
            index["records"] = []

        index["stats"]["total"] = len(index["records"]) + 1
        index["stats"]["by_type"][crystal_type.value] = index["stats"]["by_type"].get(crystal_type.value, 0) + 1
        category = CrystalCatalog.get_category_path(crystal_type)
        index["stats"]["by_category"][category] = index["stats"]["by_category"].get(category, 0) + 1
        index["stats"]["last_update"] = datetime.now().isoformat()

        index["records"].append({
            "code": crystal.get("code", ""),
            "type": crystal_type.value,
            "category": category,
            "filepath": str(filepath.relative_to(self.output_dir)),
            "counter": counter,
            "step": step,
            "quality": crystal.get("quality_score", 0)
        })

        with open(index_path, "w", encoding="utf-8") as f:
            json.dump(index, f, ensure_ascii=False, indent=2)

    def load_history(self, limit: int = None) -> List[Dict]:
        if not self.config.flags["enable_learning"]:
            return []

        index_path = self.output_dir / "meta" / "index.json"
        if not index_path.exists():
            return []

        try:
            with open(index_path, "r", encoding="utf-8") as f:
                index = json.load(f)

            records = index.get("records", [])
            if limit:
                records = records[-limit:]

            full_records = []
            for record in records:
                filepath = self.output_dir / record["filepath"]
                if filepath.exists():
                    with open(filepath, "r", encoding="utf-8") as f:
                        data = json.load(f)
                        full_records.append({
                            "code": record["code"],
                            "type": record["type"],
                            "category": record["category"],
                            "crystal": data.get("crystal", {}),
                            "meta": data.get("meta", {})
                        })
            self.history = full_records
            return full_records

        except Exception as e:
            print(f"⚠️ Ошибка загрузки истории: {e}")
            return []

