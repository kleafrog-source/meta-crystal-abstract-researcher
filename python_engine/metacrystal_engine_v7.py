        print(f"📚 Обучение: {'Включено' if self.config.flags['enable_learning'] else 'Отключено'}")

        for gen in range(generations):
            print(f"  Поколение {gen+1}/{generations}...")
            saved = self.generate_and_save_batch(batch_size, save_top)
            if saved:
                print(f"    💎 Сохранено {len(saved)} кристаллов:")
                for s in saved:
                    print(f"      {s['crystal']['code']} → {s['type'].value} ({s['filepath']})")

            batch = self.generator.generate_batch(batch_size)
            all_combinations.extend(batch)

            if len(all_combinations) > 5000:
                print(f"    Фильтрация... (всего: {len(all_combinations)})")
                all_combinations = self.filter.filter_to_emeralds(all_combinations, 200)
                print(f"    Осталось: {len(all_combinations)} изумрудов")
                self.generation_stats[gen+1] = len(all_combinations)

        print(f"\n💎 Финальный отбор из {len(all_combinations)} комбинаций...")
        self.emeralds = self.filter.filter_to_emeralds(all_combinations, 100)
        print(f"  Получено {len(self.emeralds)} изумрудов")

        if self.storage:
            print("\n💾 Сохранение изумрудов...")
            for emerald in self.emeralds[:10]:
                crystal_type = CrystalCatalog.classify(emerald)
                self.storage.save_crystal(emerald, crystal_type)

        if len(self.emeralds) >= 10:
            print("\n💎 Создание алмаза из топ-10 изумрудов...")
            top_emeralds = self.emeralds[:10]
            self.diamond = self._create_diamond(top_emeralds)
