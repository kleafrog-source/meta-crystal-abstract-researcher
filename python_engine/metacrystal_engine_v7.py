    def encode(self, combination: Dict) -> str:
        science_codes = self._extract_science_codes(combination)
        op_code = self._extract_operator_code(combination)
        psych_code = self._extract_psych_code(combination)
        pattern_code = self._extract_pattern_code(combination)

        code = (
            science_codes[:1].upper() +
            op_code.upper() +
            self._get_intensity_code(combination) +
            psych_code.upper() +
            pattern_code.upper()
        )

        hash_str = hashlib.md5(combination["combination"].encode()).hexdigest()[:3]
        return f"{code}-{hash_str}"

    def _extract_science_codes(self, combo: Dict) -> str:
        codes = []
        for elem in combo.get("elements", []):
            for science, code in self.SCIENCE_MAP.items():
                if elem in LEXICON.get(science, []):
                    codes.append(code)
                    break
        return "".join(codes[:3]) or "M"

    def _extract_operator_code(self, combo: Dict) -> str:
        for op in combo.get("operators", []):
            if op["key"] in self.OPERATOR_MAP:
                return self.OPERATOR_MAP[op["key"]]
        return "X"

    def _extract_psych_code(self, combo: Dict) -> str:
        for op in combo.get("operators", []):
            if op["key"] in self.PSYCH_MAP:
                return self.PSYCH_MAP[op["key"]]
        return "0"

    def _extract_pattern_code(self, combo: Dict) -> str:
        pattern = combo.get("pattern", "линейный")
        return self.PATTERN_MAP.get(pattern, "S")

    def _get_intensity_code(self, combo: Dict) -> str:
        combo_str = combo.get("combination", "")
        if "i" in combo_str or "π" in combo_str:
            return "C"
        if "∞" in combo_str:
            return "H"
        if "√" in combo_str:
            return "L"
        if "∂²" in combo_str or "∫∫" in combo_str:
            return "Q"
        if "∂" in combo_str:
            return "D"
        return "N"

