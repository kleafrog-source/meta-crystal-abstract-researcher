class MMSSMetrics:
    """Система метрик на основе MMSS для оценки качества комбинаций"""

    def __init__(self, config: EngineConfig):
        self.config = config
        self.targets = config.metrics_targets

    def evaluate(self, combination: Dict) -> Dict[str, float]:
        combo_str = combination.get("combination", "")

        v = self._calculate_V(combo_str)
        s = self._calculate_S(combo_str)
        n = 1 - s
        df = self._calculate_Df(combo_str)
        gs = self._calculate_G_S(combo_str)
        rt = 2.61803
        qec = self._calculate_QEC(combo_str)
        chsh = self._calculate_CHSH(combo_str)
        cval = self._calculate_C_val(combo_str)

        return {
            "V": v,
            "S": s,
            "N": n,
            "D_f": df,
            "G_S": gs,
            "R_T": rt,
            "QEC": qec,
            "CHSH": chsh,
            "C_val": cval,
            "quality_score": (v + n + (1 - s) + df/10 + qec) / 5
        }

    def _calculate_V(self, text: str) -> float:
        score = 0.5
        score += min(text.count("(") * 0.02, 0.15)
        score += min(text.count("^") * 0.03, 0.10)
        score += min(text.count("∂") * 0.05, 0.10)
        score += min(text.count("∫") * 0.05, 0.10)
        score += min(text.count("¬") * 0.03, 0.05)
        score += min(text.count("V") * 0.02, 0.05)
        score += min(text.count("G_S") * 0.03, 0.05)
        return min(score, 0.999)

    def _calculate_S(self, text: str) -> float:
        unique_chars = len(set(text))
        total_chars = len(text)
        if total_chars == 0:
            return 0.001
        entropy = unique_chars / total_chars
        return min(max(entropy * 0.01, 0.001), 0.02)

    def _calculate_Df(self, text: str) -> float:
        depth = 0
        max_depth = 0
        for ch in text:
            if ch == "(":
                depth += 1
                max_depth = max(max_depth, depth)
            elif ch == ")":
                depth -= 1
        base = 3.0
        df = base + min(max_depth * 0.2, 9.0)
        return min(df, 13.0)

    def _calculate_G_S(self, text: str) -> float:
        # Упрощённо: сложность, количество операторов, наличие этических ключей
        complexity = len(text)
        s_val = self._calculate_S(text)
        negentropy = 1 - s_val
        rt = 2.61803
        topo_defect = 1 + text.count("¬") * 0.1 + text.count("Ξ") * 0.2
        if negentropy == 0:
            return 9999.0
        gs = 1/(rt**2) * s_val / topo_defect * 1/(negentropy**2)
        return min(gs, 1000.0)

    def _calculate_QEC(self, text: str) -> float:
        v = self._calculate_V(text)
        gs = self._calculate_G_S(text)
        cval = self._calculate_C_val(text)
        qec = v * (1 - cval) * (1 - 1/(gs+1))
        return min(max(qec, 0.0), 1.0)

    def _calculate_CHSH(self, text: str) -> float:
        # Наличие операторов нелокальности и запутанности
        score = 2.0
        if "CHSH" in text or "S(" in text:
            score += 0.3
        if "|EPR⟩" in text or "Ψ_ENT" in text:
            score += 0.3
        if "nonlocality" in text or "λ" in text:
            score += 0.2
        return min(score, 2.8284)

    def _calculate_C_val(self, text: str) -> float:
        # Наличие конфликтных маркеров
        cval = 0.0
        if "¬" in text:
            cval += 0.1
        if "парадокс" in text:
            cval += 0.2
        if "конфликт" in text or "C_val" in text:
            cval += 0.3
        return min(cval, 1.0)

    def is_optimal(self, metrics: Dict[str, float]) -> bool:
        return (
            metrics["V"] >= self.targets["V"] * 0.99 and
            metrics["S"] <= self.targets["S"] * 1.1 and
            abs(metrics["D_f"] - self.targets["D_f"]) < 0.1 and
            metrics["QEC"] >= self.targets.get("QEC", 0.99) * 0.99
        )

