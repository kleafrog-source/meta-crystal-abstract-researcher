    def generate_combination(self, focus: Dict = None) -> Dict:
        if not focus:
            focus = self.get_random_focus()

        pattern = self.get_random_pattern()

        elements = []
        for _ in range(random.randint(2, self.config.max_elements)):
            elements.append(self.get_random_entity())

        ops = []
        for _ in range(len(elements) - 1):
            op = self.get_random_operator()
            ops.append(op)

        if self.config.flags["enable_psychology"] and random.random() < self.config.psychology_probability:
            psych_op = self.get_random_operator("psych")
            ops.append(psych_op)

        if (self.config.flags["enable_linguistics"] and
            self.config.flags["enable_linguistic_principles"] and
            random.random() < 0.3):
            principle = random.choice([
                "двойные-предлоги",
                "морфонологические-чередования",
                "интерфиксация-обязательность"
            ])
            elements.append(principle)

        combination = self._build_from_pattern(pattern, elements, ops)

        if self.config.use_irrational:
            degree = self._get_irrational_degree()
            combination = f"({combination}) ^ ({degree})"

        result = {
            "focus": focus,
            "pattern": pattern["name"],
            "elements": elements,
            "operators": ops,
            "combination": combination,
            "complexity": self._calculate_complexity(combination)
        }

        if self.metrics:
            result["metrics"] = self.metrics.evaluate(result)
            result["quality_score"] = result["metrics"]["quality_score"]

        return result

    def _build_from_pattern(self, pattern: Dict, elements: List[str], ops: List[Dict]) -> str:
        template = pattern["template"]
        result = template

        for i, elem in enumerate(elements[:5]):
            result = result.replace(f"{{{chr(65+i)}}}", elem)

        for i, op in enumerate(ops[:5]):
            result = result.replace(f"{{op{chr(49+i)}}}", op["symbol"])

        result = result.replace("{op}", ops[0]["symbol"] if ops else "+")
        result = result.replace("{op1}", ops[0]["symbol"] if ops else "+")
        result = result.replace("{op2}", ops[1]["symbol"] if len(ops) > 1 else "⊗")
        result = result.replace("{op3}", ops[2]["symbol"] if len(ops) > 2 else "^")
        result = result.replace("{op4}", ops[3]["symbol"] if len(ops) > 3 else "⊕")

        return result

    def _get_irrational_degree(self) -> str:
        options = ["π", "e", "√2", "√3", "φ"]
