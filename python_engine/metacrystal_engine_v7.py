class EvolutionFilter:
    """Фильтрует комбинации, оставляя изумруды"""

    def __init__(self, config: EngineConfig):
        self.config = config
        self.metrics = MMSSMetrics(config) if config.flags["enable_metrics"] else None

    def filter_to_emeralds(self, combinations: List[Dict], target: int = 100) -> List[Dict]:
        filtered = []
        for combo in combinations:
            if self._is_emerald(combo):
                filtered.append(combo)
            if len(filtered) >= target * 2:
                break

        if self.metrics and filtered and "quality_score" in filtered[0]:
            filtered.sort(key=lambda x: x.get("quality_score", 0), reverse=True)
        else:
            filtered.sort(key=lambda x: x["complexity"], reverse=True)

        return filtered[:target]

    def _is_emerald(self, combo: Dict) -> bool:
        criteria = [
            len(combo.get("elements", [])) >= 3,
            combo["complexity"] > 10,
            "¬" in combo["combination"] or "∂" in combo["combination"],
            len(combo["combination"]) > 50,
        ]

        sciences = set()
        for elem in combo.get("elements", []):
            for science in LEXICON.keys():
                if elem in LEXICON[science]:
                    sciences.add(science)
                    break
        criteria.append(len(sciences) >= 3)

        return all(criteria)

